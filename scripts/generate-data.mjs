// Generates data/backups.json - SYNTHETIC Db2 for z/OS image-copy inventory (fixed seed, reproducible).
// Usage: node scripts/generate-data.mjs
import { mkdirSync, writeFileSync } from 'node:fs';

const SEED = 42;
const AS_OF = '2026-11-19'; // fixed anchor so the dataset is identical on every run
const RETENTION_DAYS = 365; // illustrative MODIFY RECOVERY ... DELETE AGE(365)

// mulberry32 PRNG
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = rng(SEED);
const int = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));
const hex8 = () => Math.floor(rand() * 0xffffffff).toString(16).padStart(8, '0');
const pad = (n, w = 2) => String(n).padStart(w, '0');

// Fictional bank "Meridian Financial"; high-level qualifier MRDN is fictional.
const OBJECTS = [
  { ts: 'ACCTDB.ACCTLEDG', code: 'ACLG', desc: 'General ledger entries' },
  { ts: 'ACCTDB.ACCTMAST', code: 'ACMS', desc: 'Account master' },
  { ts: 'CUSTDB.CUSTMAST', code: 'CUMS', desc: 'Customer master' },
  { ts: 'PAYDB.PAYHIST', code: 'PYHS', desc: 'Payment history' },
  { ts: 'CARDDB.CARDTXN', code: 'CDTX', desc: 'Card transactions' },
  { ts: 'RISKDB.RISKSCOR', code: 'RKSC', desc: 'Risk scores' },
];

// Forced gaps so the demo can show an honest "cannot be proven" outcome.
const FORCED_GAPS = new Set(['PAYDB.PAYHIST|2023-12-31', 'CARDDB.CARDTXN|2024-05-31']);

const asOf = new Date(`${AS_OF}T00:00:00Z`);
const julian = (d) => {
  const start = Date.UTC(d.getUTCFullYear(), 0, 0);
  return pad(Math.floor((d.getTime() - start) / 86400000), 3);
};
const iso = (d) => d.toISOString().slice(0, 10);
const monthsBetween = (d) => (asOf.getUTCFullYear() - d.getUTCFullYear()) * 12 + (asOf.getUTCMonth() - d.getUTCMonth());

const backups = [];
// Month-end full image copies for Oct-2023 .. Oct-2026 (37 month-ends, 6 objects each)
for (let i = 37; i >= 1; i--) {
  const monthEnd = new Date(Date.UTC(asOf.getUTCFullYear(), asOf.getUTCMonth() - i + 1, 0));
  const ageDays = Math.floor((asOf - monthEnd) / 86400000);
  const m = monthsBetween(monthEnd);
  for (const o of OBJECTS) {
    const [db, name] = o.ts.split('.');
    const copyDate = iso(monthEnd);
    const retained = ageDays <= RETENTION_DAYS;
    const gap = FORCED_GAPS.has(`${o.ts}|${copyDate}`);
    const tier = m <= 3 ? 'DASD' : m <= 15 ? 'HSM ML2' : 'Virtual tape';
    const volser = gap ? '-' : tier === 'DASD' ? `PRD${pad(int(1, 40))}` : tier === 'HSM ML2' ? `HSM${pad(int(1, 99), 3)}` : `VT0${pad(int(100, 999), 3)}`;
    backups.push({
      id: `BKP-${hex8()}`,
      tablespace: o.ts,
      copyDate,
      copyTime: `23:${pad(int(5, 58))}`,
      copyType: 'FULL',
      jobName: `${o.code}ICPY`,
      jobStep: 'IC010',
      dataset: `MRDN.DB2P.${db}.${name}.FC.D${monthEnd.getUTCFullYear()}${julian(monthEnd)}`,
      tier: gap ? 'Not found' : tier,
      volser,
      sizeGb: Math.round((8 + rand() * 132) * 10) / 10,
      evidenceSource: retained ? 'SYSCOPY' : 'ADDI lineage',
      status: gap ? 'gap' : retained ? 'validated' : 'located',
    });
  }
}

// Monthly roll-up for the dashboard chart
const monthly = [];
const byMonth = new Map();
for (const b of backups) {
  const k = b.copyDate.slice(0, 7);
  if (!byMonth.has(k)) byMonth.set(k, { sys: 0, addi: 0, gap: 0 });
  const e = byMonth.get(k);
  if (b.status === 'gap') e.gap++;
  else if (b.evidenceSource === 'SYSCOPY') e.sys++;
  else e.addi++;
}
for (const [month, e] of byMonth) {
  monthly.push({ group: 'Db2 catalog (SYSCOPY)', key: month, value: e.sys });
  monthly.push({ group: 'Recovered via ADDI lineage', key: month, value: e.addi });
  monthly.push({ group: 'Gap (not provable)', key: month, value: e.gap });
}

const out = {
  _synthetic: true,
  _note: 'SYNTHETIC DATA. Fictional bank, fictional dataset names and volsers. Generated by scripts/generate-data.mjs with seed 42.',
  seed: SEED,
  asOf: AS_OF,
  syscopyRetentionDays: RETENTION_DAYS,
  objects: OBJECTS,
  backups,
  monthly,
};

mkdirSync(new URL('../data/', import.meta.url), { recursive: true });
writeFileSync(new URL('../data/backups.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
console.log(`Wrote data/backups.json: ${backups.length} backups, ${backups.filter((b) => b.status === 'gap').length} gaps`);
